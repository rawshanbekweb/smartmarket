let currentLang: Lang = 'uz';

/**
 * Translate a phrase written in Uzbek: `tx("Saqlandi")`, `tx("{n} ta yozuv", { n })`.
 * Works outside components too (formatters, API error text); the tree re-renders on a language switch.
 */
export function tx(uz: string, vars?: Record<string, string | number>): string {
  let s = uz;
  if (currentLang === 'ru') {
    const ru = P[uz];
    if (ru !== undefined) s = ru;
    else if (import.meta.env.DEV) console.warn(`[i18n] no Russian translation for: ${uz}`);
  }
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Same as `tx` for text that comes from the API (report titles, setting descriptions, errors): unknown text passes through. */
export function txServer(text: string): string {
  if (currentLang !== 'ru') return text;
  const exact = P[text];
  if (exact !== undefined) return exact;
  for (const [re, ru] of PATTERNS) if (re.test(text)) return text.replace(re, ru);
  return text;
}

